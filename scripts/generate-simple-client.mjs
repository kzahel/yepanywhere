/** Deliberately small JSON Schema emitter for the offline simple-client spike.
 * Unsupported schema vocabulary fails generation rather than weakening a decoder.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";
import { validateSimpleClientSchema } from "./lib/simple-client-schema.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
if (process.argv.slice(2).some((arg) => arg !== "--check"))
  throw new Error("Use --check or no arguments");
const schema = JSON.parse(
  readFileSync(
    resolve(root, "packages/shared/contracts/simple-client.schema.json"),
    "utf8",
  ),
);
validateSimpleClientSchema(schema);
const defs = schema.$defs;
const quote = JSON.stringify;
const refName = (s) => s.$ref.slice("#/$defs/".length);
const members = new Map();
for (const [name, s] of Object.entries(defs)) {
  if (!s["x-open-kind"]) continue;
  for (const branch of s.oneOf.slice(0, -1)) {
    const type = refName(branch);
    if (members.has(type))
      throw new Error(
        "A record cannot belong to multiple unions in this spike",
      );
    members.set(type, name);
  }
}
const order = [];
const visiting = new Set();
function visit(name) {
  if (order.includes(name)) return;
  if (visiting.has(name)) throw new Error(`Recursive definition: ${name}`);
  if (!defs[name]) throw new Error(`Missing definition: ${name}`);
  visiting.add(name);
  function refs(s) {
    if (s && typeof s === "object") {
      if (s.$ref) {
        if (!s.$ref.startsWith("#/$defs/"))
          throw new Error("Only local references supported");
        visit(refName(s));
      } else Object.values(s).forEach(refs);
    }
  }
  refs(defs[name]);
  visiting.delete(name);
  order.push(name);
}
Object.keys(defs).forEach(visit);

function tsType(s) {
  if (s.$ref) return refName(s);
  if (s.const !== undefined) return quote(s.const);
  if (s.enum) return s.enum.map(quote).join(" | ");
  if (s.anyOf) return `${tsType(s.anyOf[0])} | null`;
  if (s["x-open-kind"])
    return [...s.oneOf.slice(0, -1).map(tsType), "UnknownVariant"].join(" | ");
  if (s.type === "object")
    return `{ ${Object.entries(s.properties)
      .map(([k, v]) => `${k}: ${tsType(v)};`)
      .join(" ")} }`;
  if (s.type === "array") return `Array<${tsType(s.items)}>`;
  return s.type === "integer" ? "number" : s.type;
}
function tsDecoder(s) {
  if (s.$ref) return `${refName(s)}Schema`;
  if (s.const !== undefined) return `z.literal(${quote(s.const)})`;
  if (s.enum) return `z.enum(${quote(s.enum)})`;
  if (s.anyOf) return `${tsDecoder(s.anyOf[0])}.nullable()`;
  if (s.type === "object")
    return `z.object({${Object.entries(s.properties)
      .map(([k, v]) => `${k}: ${tsDecoder(v)}`)
      .join(",")}})`;
  if (s.type === "array")
    return `z.array(${tsDecoder(s.items)}).min(${s.minItems}).max(${s.maxItems})`;
  if (s.type === "integer")
    return `z.number().int().min(${s.minimum}).max(${s.maximum})`;
  if (s.type === "boolean") return "z.boolean()";
  return `z.string().refine(v => Array.from(v).length >= ${s.minLength} && Array.from(v).length <= ${s.maxLength}, "String length out of bounds")${s.pattern ? `.regex(/${s.pattern}/)` : ""}`;
}
let ts = `// Generated by scripts/generate-simple-client.mjs. Edit the JSON Schema source.\nimport { z } from "zod";\n
export type UnknownVariant = { kind: "unknown"; originalKind: string; raw: Record<string, unknown> };
function openUnion<T>(variants: Record<string, z.ZodType<T>>): z.ZodType<T | UnknownVariant> {
  return z.unknown().transform((raw, ctx): T | UnknownVariant => {
    const tag = z.object({kind: z.string().refine(v => Array.from(v).length >= 1 && Array.from(v).length <= 128)}).passthrough().safeParse(raw);
    if (!tag.success) { ctx.addIssue({code: "custom", message: "Expected an object with kind"}); return z.NEVER; }
    const decoder = Object.hasOwn(variants, tag.data.kind) ? variants[tag.data.kind] : undefined;
    if (!decoder) return {kind: "unknown", originalKind: tag.data.kind, raw: structuredClone(tag.data)};
    const decoded = decoder.safeParse(raw);
    if (!decoded.success) { ctx.addIssue({code: "custom", message: \`Malformed known variant: \${tag.data.kind}\`}); return z.NEVER; }
    return decoded.data;
  });
}
`;
for (const name of order) {
  const s = defs[name];
  ts += `export type ${name} = ${tsType(s)};\n`;
  const expression = s["x-open-kind"]
    ? `openUnion<Exclude<${name}, UnknownVariant>>({${s.oneOf
        .slice(0, -1)
        .map(
          (r) =>
            `${quote(defs[refName(r)].properties.kind.const)}: ${refName(r)}Schema`,
        )
        .join(",")}})`
    : tsDecoder(s);
  ts += `export const ${name}Schema: z.ZodType<${name}> = ${expression};\n`;
}
ts += `export const MAX_SNAPSHOT_BYTES = 262144;\nexport function decodeSnapshot(encoded: string): SnapshotEnvelope {
  if (new TextEncoder().encode(encoded).length > MAX_SNAPSHOT_BYTES) throw new Error("Snapshot byte limit exceeded");
  return SnapshotEnvelopeSchema.parse(JSON.parse(encoded));
}\n`;

function ktType(s) {
  if (s.$ref) return refName(s);
  if (s.anyOf) return `${ktType(s.anyOf[0])}?`;
  if (s.type === "array") return `List<${ktType(s.items)}>`;
  if (s.const !== undefined)
    return typeof s.const === "boolean"
      ? "Boolean"
      : typeof s.const === "number"
        ? "Int"
        : "String";
  return { string: "String", integer: "Int", boolean: "Boolean" }[s.type];
}
function ktDecoder(s, value) {
  if (s.$ref) return `decode${refName(s)}(${value})`;
  if (s.anyOf)
    return `${value}.let { if (it == JSONObject.NULL) null else ${ktDecoder(s.anyOf[0], "it")} }`;
  if (s.const !== undefined)
    return `${ktDecoder({ type: ktType(s) === "Int" ? "integer" : ktType(s) === "Boolean" ? "boolean" : "string", minLength: 0, maxLength: 1000, minimum: -2147483648, maximum: 2147483647 }, value)}.also { require(it == ${quote(s.const)}) { "Unexpected constant" } }`;
  if (s.type === "array")
    return `arrayValue(${value}, ${s.minItems}, ${s.maxItems}).map { ${ktDecoder(s.items, "it")} }`;
  if (s.type === "integer")
    return `intValue(${value}, ${s.minimum}, ${s.maximum})`;
  if (s.type === "boolean") return `booleanValue(${value})`;
  return `stringValue(${value}, ${s.minLength}, ${s.maxLength})${s.pattern ? `.also { require(Regex(${quote(s.pattern)}).matches(it)) { "Invalid string format" } }` : ""}`;
}
let kt = `// Generated by scripts/generate-simple-client.mjs. Edit the JSON Schema source.
package com.yepanywhere.mobile.experimental

import org.json.JSONArray
import org.json.JSONObject

`;
for (const name of order) {
  const s = defs[name];
  if (s["x-open-kind"])
    kt += `sealed interface ${name} {\n    data class Unknown(val originalKind: String, val raw: JSONObject) : ${name}\n}\n\n`;
  else if (s.type === "object")
    kt += `data class ${name}(\n${Object.entries(s.properties)
      .map(([k, v]) => `    val ${k}: ${ktType(v)},`)
      .join("\n")}\n)${members.has(name) ? ` : ${members.get(name)}` : ""}\n\n`;
  else if (s.enum)
    kt += `enum class ${name}(val wire: String) {\n${s.enum.map((v) => `    ${v.replace(/([a-z])([A-Z])/g, "$1_$2").toUpperCase()}(${quote(v)})`).join(",\n")}\n}\n\n`;
  else kt += `typealias ${name} = ${ktType(s)}\n\n`;
}
kt += `object SimpleClientContract {
    const val MAX_SNAPSHOT_BYTES = 262144
    fun decodeSnapshot(encoded: String): SnapshotEnvelope {
        require(encoded.toByteArray(Charsets.UTF_8).size <= MAX_SNAPSHOT_BYTES) { "Snapshot byte limit exceeded" }
        return decodeSnapshotEnvelope(JSONObject(encoded))
    }
    private fun objectValue(value: Any): JSONObject = value as? JSONObject ?: error("Expected object")
    private fun field(obj: JSONObject, name: String): Any {
        require(obj.has(name)) { "Missing field: $name" }
        return obj.get(name)
    }
    private fun stringValue(value: Any, min: Int, max: Int): String {
        require(value is String) { "Expected string" }
        require(value.codePointCount(0, value.length) in min..max) { "String length out of bounds" }
        return value
    }
    private fun intValue(value: Any, min: Int, max: Int): Int {
        require(value is Number) { "Expected number" }
        val number = value.toDouble()
        require(number.isFinite() && number >= min && number <= max && number % 1.0 == 0.0) { "Invalid integer" }
        return number.toInt()
    }
    private fun booleanValue(value: Any): Boolean {
        require(value is Boolean) { "Expected boolean" }
        return value
    }
    private fun arrayValue(value: Any, min: Int, max: Int): List<Any> {
        require(value is JSONArray && value.length() in min..max) { "Invalid array" }
        return List(value.length()) { value.get(it) }
    }
`;
for (const name of order) {
  const s = defs[name];
  kt += `\n    fun decode${name}(value: Any): ${name} {\n`;
  if (s["x-open-kind"])
    kt += `        val obj = objectValue(value)\n        return when (val kind = stringValue(field(obj, "kind"), 1, 128)) {\n${s.oneOf
      .slice(0, -1)
      .map(
        (r) =>
          `            ${quote(defs[refName(r)].properties.kind.const)} -> decode${refName(r)}(obj)`,
      )
      .join(
        "\n",
      )}\n            else -> ${name}.Unknown(kind, JSONObject(obj.toString()))\n        }\n`;
  else if (s.type === "object")
    kt += `        val obj = objectValue(value)\n        return ${name}(\n${Object.entries(
      s.properties,
    )
      .map(
        ([k, v]) =>
          `            ${k} = ${ktDecoder(v, `field(obj, ${quote(k)})`)},`,
      )
      .join("\n")}\n        )\n`;
  else if (s.enum)
    kt += `        val wire = value as? String ?: error("Expected enum string")\n        return ${name}.entries.firstOrNull { it.wire == wire } ?: error("Unknown ${name}")\n`;
  else kt += `        return ${ktDecoder(s, "value")}\n`;
  kt += "    }\n";
}
kt += "}\n";
const tsPath = "packages/shared/src/experimental/simple-client.generated.ts";
const formatted = spawnSync(
  process.execPath,
  [resolve(root, "scripts/biome.cjs"), "format", `--stdin-file-path=${tsPath}`],
  { cwd: root, input: ts, encoding: "utf8" },
);
if (formatted.status !== 0) throw new Error(formatted.stderr);
const outputs = [
  [tsPath, formatted.stdout],
  [
    "packages/android/app/src/main/java/com/yepanywhere/mobile/experimental/SimpleClientContract.generated.kt",
    kt,
  ],
];
for (const [path, content] of outputs) {
  const absolute = resolve(root, path);
  if (check) {
    if (readFileSync(absolute, "utf8") !== content)
      throw new Error(`Stale generated contract: ${path}`);
  } else writeFileSync(absolute, content);
}
console.log(
  `${check ? "Verified" : "Generated"} TypeScript and Kotlin contracts (${order.length} definitions)`,
);
